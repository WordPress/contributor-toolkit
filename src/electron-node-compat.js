// Routes `createHash('shake256', …)` to the hash above, and only when the
// runtime's own createHash cannot do it, so on plain Node this changes nothing.
// Every other algorithm still goes to the runtime. Returns whether it patched.
function provideShake256(crypto = require('node:crypto')) {
	try {
		crypto.createHash('shake256', { outputLength: 16 });
		return false;
	} catch {
		// Fall through: the runtime has no SHAKE256.
	}
	const nativeCreateHash = crypto.createHash;
	crypto.createHash = function createHash(algorithm, options) {
		if (typeof algorithm === 'string' && algorithm.toLowerCase() === 'shake256') {
			return new Shake256(options);
		}
		return nativeCreateHash.apply(this, arguments);
	};
	return true;
}

// Only self-applies when the app explicitly asked for it, so requiring this
// module from a test never mutates the test process.
if (process.env.WPTK_NODE_COMPAT === '1') {
	hideElectronRuntime(process);
	provideShake256();
}

