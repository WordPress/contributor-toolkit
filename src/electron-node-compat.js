// Preloaded (via NODE_OPTIONS=--require) into every descendant Node process, so
// that the tools this app spawns see the plain Node they are actually running
// on.
//
// Why this is needed: the only `node` on PATH is the shim written by
// ensureNodeShimDir() in main.js, and that shim is Electron under
// ELECTRON_RUN_AS_NODE. Electron keeps `process.versions.electron` set in that
// mode, and a command-line tool built on yargs reads exactly that to decide
// where its arguments begin — `yargs/helpers.hideBin` reads "electron set,
// defaultApp unset" as a packaged Electron app and slices argv one element
// short. Every such tool then sees its own executable path as the first
// argument it was passed.
//
// For a task runner that extra argument is a command to run, so it runs itself
// with no arguments, and the copy it starts does the same, without end: a
// Gutenberg build reached ~1300 processes before the machine gave out (#275).
// The runaway processes are only the loudest form of the failure — the general
// one is that every yargs-based tool reached through the shim misreads its
// arguments, quietly.
//
// Deliberately self-contained (no requires beyond Node's own `node:crypto`): this file is copied into the
// temp shim dir and required from there, because --require into a path inside
// app.asar is not reliable under ELECTRON_RUN_AS_NODE.

// Only `versions.electron` is hidden, and the narrowness is load-bearing.
//
// `versions.chrome` was hidden alongside it at first — it is the other half of
// how the runtime describes itself — and that broke Gutenberg's bundling step
// outright, while the recursion it was meant to help with was already gone.
// Build tooling reads `chrome` to decide what it is compiling for, which is a
// question about the output, not about who is running the compiler. `versions.v8`
// carries an `-electron` suffix and is left alone for the same reason, plus a
// blunter one: tools parse it as a version number.
//
// So this hides the runtime from code asking "am I inside Electron?", and hides
// nothing from code asking "what can I emit?".
const ELECTRON_VERSION_KEYS = ['electron'];

// Returns the keys actually removed, so a caller (and the tests) can tell the
// difference between "nothing to hide" and "could not hide it". A frozen
// `versions` object would make the delete a silent no-op in sloppy mode, hence
// re-reading the key rather than trusting `delete`'s return value.
// A default parameter, not `proc || process`: falling back on a null argument
// would quietly strip the *current* process, which under the Electron test pass
// is the suite itself.
function hideElectronRuntime(proc = process) {
	const versions = proc && proc.versions;
	if (!versions) return [];
	const hidden = [];
	for (const key of ELECTRON_VERSION_KEYS) {
		if (versions[key] === undefined) continue;
		delete versions[key];
		if (versions[key] === undefined) hidden.push(key);
	}
	return hidden;
}

// SHAKE256, which Electron's crypto does not have.
//
// Electron builds Node against BoringSSL, not OpenSSL, and BoringSSL has no
// SHA-3 family: `createHash('shake256')` throws "Digest method not supported".
// npm's isolated installer names every directory under node_modules/.store with
// a 16-byte SHAKE256 (@npmcli/arborist, isolated-reifier.js), so any project
// whose .npmrc says `install-strategy = "linked"` fails `npm install` before it
// writes anything. Gutenberg switched to it in WordPress/gutenberg#83847.
//
// The hash below is the real SHAKE256 (FIPS 202), not a stand-in: the .store
// names it produces are the ones a contributor gets on plain Node, so a
// node_modules built by the app and one built outside it agree.
//
// Keccak-f[1600] on 32-bit halves of each lane, because BigInt is far too slow
// for the volume npm hashes. Lane i (x + 5y) is state[2i] (low) and
// state[2i + 1] (high).
/* eslint-disable no-bitwise -- Keccak is defined in XORs, ANDs and rotations of 64-bit lanes; there is no other way to write it. */
const SHAKE256_RATE = 136;
const SHAKE256_DEFAULT_LENGTH = 32;

// Rotation offset for lane x + 5y.
const KECCAK_ROTATIONS = [
	0, 1, 62, 28, 27,
	36, 44, 6, 55, 20,
	3, 10, 43, 25, 39,
	41, 45, 15, 21, 8,
	18, 2, 61, 56, 14
];

// The 24 round constants, generated by the LFSR FIPS 202 defines them with
// rather than typed out, as [low, high] pairs.
const KECCAK_ROUND_CONSTANTS = (() => {
	let lfsr = 1;
	const nextBit = () => {
		const bit = lfsr & 1;
		lfsr = (lfsr & 0x80) ? ((lfsr << 1) ^ 0x71) & 0xff : (lfsr << 1) & 0xff;
		return bit;
	};
	const constants = [];
	for (let round = 0; round < 24; round++) {
		let lo = 0;
		let hi = 0;
		for (let j = 0; j < 7; j++) {
			if (!nextBit()) continue;
			const position = (1 << j) - 1;
			if (position < 32) lo ^= 1 << position;
			else hi ^= 1 << (position - 32);
		}
		constants.push([lo >>> 0, hi >>> 0]);
	}
	return constants;
})();

function keccakF1600(state) {
	const c = new Uint32Array(10);
	const b = new Uint32Array(50);
	for (let round = 0; round < 24; round++) {
		// θ
		for (let x = 0; x < 5; x++) {
			c[2 * x] = state[2 * x] ^ state[2 * x + 10] ^ state[2 * x + 20] ^ state[2 * x + 30] ^ state[2 * x + 40];
			c[2 * x + 1] = state[2 * x + 1] ^ state[2 * x + 11] ^ state[2 * x + 21] ^ state[2 * x + 31] ^ state[2 * x + 41];
		}
		for (let x = 0; x < 5; x++) {
			const left = (x + 4) % 5;
			const right = (x + 1) % 5;
			const rlo = c[2 * right];
			const rhi = c[2 * right + 1];
			const dlo = c[2 * left] ^ ((rlo << 1) | (rhi >>> 31));
			const dhi = c[2 * left + 1] ^ ((rhi << 1) | (rlo >>> 31));
			for (let y = 0; y < 25; y += 5) {
				state[2 * (x + y)] ^= dlo;
				state[2 * (x + y) + 1] ^= dhi;
			}
		}
		// ρ and π
		for (let x = 0; x < 5; x++) {
			for (let y = 0; y < 5; y++) {
				const from = x + 5 * y;
				const to = y + 5 * ((2 * x + 3 * y) % 5);
				const lo = state[2 * from];
				const hi = state[2 * from + 1];
				const n = KECCAK_ROTATIONS[from];
				if (n === 0) {
					b[2 * to] = lo;
					b[2 * to + 1] = hi;
				} else if (n < 32) {
					b[2 * to] = (lo << n) | (hi >>> (32 - n));
					b[2 * to + 1] = (hi << n) | (lo >>> (32 - n));
				} else if (n === 32) {
					b[2 * to] = hi;
					b[2 * to + 1] = lo;
				} else {
					const m = n - 32;
					b[2 * to] = (hi << m) | (lo >>> (32 - m));
					b[2 * to + 1] = (lo << m) | (hi >>> (32 - m));
				}
			}
		}
		// χ
		for (let y = 0; y < 25; y += 5) {
			for (let x = 0; x < 5; x++) {
				const i = x + y;
				const i1 = ((x + 1) % 5) + y;
				const i2 = ((x + 2) % 5) + y;
				state[2 * i] = b[2 * i] ^ (~b[2 * i1] & b[2 * i2]);
				state[2 * i + 1] = b[2 * i + 1] ^ (~b[2 * i1 + 1] & b[2 * i2 + 1]);
			}
		}
		// ι
		state[0] ^= KECCAK_ROUND_CONSTANTS[round][0];
		state[1] ^= KECCAK_ROUND_CONSTANTS[round][1];
	}
}

// The part of Node's Hash that callers of createHash('shake256') use:
// update() any number of times, then one digest(), with or without an encoding.
class Shake256 {
	constructor(options) {
		const length = options && options.outputLength !== undefined
			? options.outputLength
			: SHAKE256_DEFAULT_LENGTH;
		if (!Number.isInteger(length) || length < 0) {
			throw new RangeError(`Invalid outputLength for shake256: ${length}`);
		}
		this.outputLength = length;
		this.state = new Uint32Array(50);
		this.position = 0;
		this.finalized = false;
	}

	update(data, inputEncoding) {
		if (this.finalized) throw new Error('Digest already called');
		const bytes = typeof data === 'string'
			? Buffer.from(data, inputEncoding || 'utf8')
			: Buffer.from(data.buffer, data.byteOffset, data.byteLength);
		const state = this.state;
		let position = this.position;
		for (let k = 0; k < bytes.length; k++) {
			state[position >> 2] ^= bytes[k] << (8 * (position & 3));
			if (++position === SHAKE256_RATE) {
				keccakF1600(state);
				position = 0;
			}
		}
		this.position = position;
		return this;
	}

	digest(outputEncoding) {
		if (this.finalized) throw new Error('Digest already called');
		this.finalized = true;
		const state = this.state;
		// SHAKE's domain bits and the final bit of pad10*1.
		state[this.position >> 2] ^= 0x1f << (8 * (this.position & 3));
		state[(SHAKE256_RATE - 1) >> 2] ^= 0x80 << (8 * ((SHAKE256_RATE - 1) & 3));
		keccakF1600(state);
		const out = Buffer.alloc(this.outputLength);
		let position = 0;
		for (let k = 0; k < out.length; k++) {
			if (position === SHAKE256_RATE) {
				keccakF1600(state);
				position = 0;
			}
			out[k] = (state[position >> 2] >>> (8 * (position & 3))) & 0xff;
			position++;
		}
		return outputEncoding ? out.toString(outputEncoding) : out;
	}
}

